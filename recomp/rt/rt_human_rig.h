inline const HumanTorso *human_torso(int frame) {
    int first = 0, last = int(sizeof(human_torsos) / sizeof(human_torsos[0]));
    while (first < last) {
        int mid = (first + last) / 2;
        if (human_torsos[mid].frame < frame) first = mid + 1; else last = mid;
    }
    return first < int(sizeof(human_torsos) / sizeof(human_torsos[0])) && human_torsos[first].frame == frame ? &human_torsos[first] : nullptr;
}
inline bool torso_records_match(const HumanTorso &pose, int first, int end, const int *upper, const int *lower) {
    if (!upper || pose.record < first || pose.record >= end) return false;
    if (upper[0] != pose.image || upper[1] != pose.recordX || upper[2] != pose.recordY ||
        (upper[4] != 0 && upper[4] != 9 && upper[4] != 13)) return false;
    if (pose.hideRecord >= 0 && (!lower || pose.hideRecord < first || pose.hideRecord >= end ||
        lower[0] != pose.hideImage || lower[4] != 0)) return false;
    const float dx = pose.hipX - pose.neckX, dy = pose.hipY - pose.neckY;
    return dx * dx + dy * dy >= 400 && dx * dx + dy * dy <= 6400;
}
